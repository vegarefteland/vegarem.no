#!/usr/bin/env node
/* ============================================================================
 * build-share-pages.js — a link preview per project
 *
 * WHY THIS EXISTS
 * When a link is pasted into LinkedIn, iMessage, Slack etc., their crawlers
 * read the page's <meta property="og:…"> tags without running any
 * JavaScript. The site is one index.html that builds every page in JS, so
 * every shared link used to show the same generic preview.
 *
 * This writes a tiny static page for each project at /<slug>/index.html
 * (GitHub Pages serves it for vegarem.no/<slug>) carrying that project's
 * title, description and image. A visitor's browser is sent straight on to
 * the real site, the same way 404.html does it, so people never see it.
 *
 * Also writes images/share/<folder>.jpg — a 1200×630 crop of the cover,
 * which is the size link previews expect (covers can be video, and a
 * preview image can't). Only regenerated when the cover changes.
 *
 * Pages for projects that were renamed or removed are deleted again: every
 * generated page carries the SHARE_MARK comment, and only those are touched.
 *
 * YOU DON'T NEED TO RUN THIS BY HAND — the pre-commit hook does. To preview:
 *     node scripts/build-share-pages.js
 * ========================================================================= */

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const SITE_URL = "https://vegarem.no";
const OWNER = "Vegar Efteland Melhus";
const SHARE_DIR = path.join(ROOT, "images", "share");
const SHARE_MARK = "share-page: generated by scripts/build-share-pages.js";

// content.js declares `const SITE = {…}` — run it and hand SITE back out.
const ctx = {};
vm.runInNewContext(fs.readFileSync(path.join(ROOT, "content.js"), "utf8") + "\n;this.SITE = SITE;", ctx);
const SITE = ctx.SITE;

// Must match slugify() in index.html, or the links won't line up.
const slugify = str => str.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const esc = s => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// "01 – Knurr Display" → "Knurr Display": the number is for the grid, not a preview.
const cleanTitle = t => t.replace(/^\s*\d+\s*[–—-]\s*/, "").trim();

// First real paragraph of the description (skips short lead-ins like
// "Student Project in collaboration with:"), tags stripped, ~155 chars.
function summary(desc) {
  const paras = String(desc || "").split(/\n+/)
    .map(p => p.replace(/<br\s*\/?>/gi, " ").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim())
    .filter(Boolean);
  let text = paras.find(p => p.length >= 60) || paras[0] || "";
  if (text.length > 155) text = text.slice(0, 155).replace(/\s+\S*$/, "") + "…";
  return text;
}

const FFMPEG = ["ffmpeg", "/opt/homebrew/bin/ffmpeg", "/usr/local/bin/ffmpeg"];
function ffmpeg(args, capture) {
  for (const bin of FFMPEG) {
    try { const out = execFileSync(bin, args, { stdio: ["ignore", capture ? "pipe" : "ignore", "ignore"], maxBuffer: 1 << 20 }); return capture ? out : true; }
    catch (e) { if (e.code !== "ENOENT") return false; }
  }
  return null;   // no ffmpeg anywhere
}

/* For a video cover, the moment with the most going on: sample a dozen
   points across the clip as tiny 32×17 frames and score each by contrast
   (spread of brightness) plus a little for brightness itself. A clip that
   sits on black most of the time — like the Motion cover — would otherwise
   preview as a black rectangle. */
function bestMoment(src) {
  let duration = 0;
  for (const bin of ["ffprobe", "/opt/homebrew/bin/ffprobe", "/usr/local/bin/ffprobe"]) {
    try {
      duration = parseFloat(execFileSync(bin, ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", src]).toString()) || 0;
      break;
    } catch (e) { if (e.code !== "ENOENT") break; }
  }
  if (!duration) return 0;
  let best = 0, bestScore = -1;
  for (let i = 1; i <= 12; i++) {
    const at = duration * i / 13;
    const buf = ffmpeg(["-v", "error", "-ss", at.toFixed(2), "-i", src, "-frames:v", "1",
      "-vf", "scale=32:17", "-f", "rawvideo", "-pix_fmt", "gray", "-"], true);
    if (!buf || !buf.length) continue;
    let sum = 0, sq = 0;
    for (const v of buf) { sum += v; sq += v * v; }
    const mean = sum / buf.length, sd = Math.sqrt(Math.max(0, sq / buf.length - mean * mean));
    const score = sd + mean * 0.3;
    if (score > bestScore) { bestScore = score; best = at; }
  }
  return best;
}

// 1200×630 JPEG of the cover. Videos use the liveliest frame (bestMoment).
let ffmpegMissing = false;
function shareImage(project) {
  const src = path.join(ROOT, project.cover);
  if (!fs.existsSync(src)) return null;
  const out = path.join(SHARE_DIR, project.folder + ".jpg");
  const fresh = fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(src).mtimeMs;
  if (!fresh && !ffmpegMissing) {
    fs.mkdirSync(SHARE_DIR, { recursive: true });
    const isVid = /\.(mp4|webm|mov)$/i.test(src);
    const fit = "scale=1200:630:force_original_aspect_ratio=increase,crop=1200:630";
    const seek = isVid ? ["-ss", bestMoment(src).toFixed(2)] : [];
    const ok = ffmpeg(["-v", "error", "-y", ...seek, "-i", src,
      "-vf", fit, "-frames:v", "1", "-q:v", "3", out]);
    if (ok === null) ffmpegMissing = true;
  }
  return fs.existsSync(out) ? `images/share/${project.folder}.jpg` : null;
}

function page({ slug, title, description, image }) {
  const url = `${SITE_URL}/${slug}`;
  const full = `${title} — ${OWNER}`;
  const img = image ? `${SITE_URL}/${image}` : null;
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <!-- ${SHARE_MARK}. Do not edit by hand. -->
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${esc(full)}</title>
  <meta name="description" content="${esc(description)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="${esc(OWNER)}">
  <meta property="og:url" content="${url}">
  <meta property="og:title" content="${esc(full)}">
  <meta property="og:description" content="${esc(description)}">
${img ? `  <meta property="og:image" content="${img}">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
` : ""}  <meta name="twitter:card" content="${img ? "summary_large_image" : "summary"}">
  <meta name="twitter:title" content="${esc(full)}">
  <meta name="twitter:description" content="${esc(description)}">
${img ? `  <meta name="twitter:image" content="${img}">
` : ""}  <script>
    // People go straight on to the real page; index.html reads ?p= and puts
    // the address back to /${slug} (same route 404.html uses).
    location.replace("/?p=" + encodeURIComponent(${JSON.stringify(slug)}) + location.hash);
  </script>
</head>
<body>
  <noscript><p><a href="/">${esc(title)} — open the portfolio</a></p></noscript>
</body>
</html>
`;
}

// ── build ──────────────────────────────────────────────────────────────
const wanted = new Set();
const images = new Set();
for (const project of SITE.projects || []) {
  if (project.wip || /^WIP_/i.test(project.folder)) continue;
  const slug = slugify(project.title);
  if (!slug || slug === "about" || slug === "archive") continue;
  const image = shareImage(project);
  if (image) images.add(path.basename(image));
  const dir = path.join(ROOT, slug);
  const file = path.join(dir, "index.html");
  // Never overwrite a real folder that happens to share the name.
  if (fs.existsSync(dir) && !(fs.existsSync(file) && fs.readFileSync(file, "utf8").includes(SHARE_MARK))) {
    console.log(`  skipped /${slug}: a folder by that name already exists`);
    continue;
  }
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(file, page({ slug, title: cleanTitle(project.title), description: summary(project.description), image }));
  wanted.add(slug);
}

// ── clean up pages/images for renamed or removed projects ──────────────
for (const name of fs.readdirSync(ROOT)) {
  const file = path.join(ROOT, name, "index.html");
  if (wanted.has(name) || !fs.existsSync(file)) continue;
  if (fs.readFileSync(file, "utf8").includes(SHARE_MARK)) {
    fs.rmSync(path.join(ROOT, name), { recursive: true, force: true });
    console.log(`  removed stale /${name}`);
  }
}
if (fs.existsSync(SHARE_DIR)) {
  for (const f of fs.readdirSync(SHARE_DIR)) {
    if (f.endsWith(".jpg") && !images.has(f)) fs.rmSync(path.join(SHARE_DIR, f));
  }
}

console.log(`share pages written (${wanted.size}): ${[...wanted].map(s => "/" + s).join("  ")}`);
if (ffmpegMissing) console.log("  note: ffmpeg not found — preview images not (re)generated");
